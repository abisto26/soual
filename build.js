// Builds index.html and sw.js from src/. Run: node build.js
const fs = require('fs'), crypto = require('crypto');
const rd = f => fs.readFileSync(f, 'utf8');
const html = rd('src/game.src.html').replace('__ICONS__', () => rd('src/social-icons.html').trimEnd());
fs.writeFileSync('index.html', html);
const files = ['./', 'index.html', 'questions.js', 'manifest.webmanifest', 'assets/logo.webp', 'assets/logo-sm.webp',
  ...fs.readdirSync('assets/fonts').map(f => 'assets/fonts/' + f), 'icons/favicon.png', 'icons/apple-touch-icon.png', 'icons/icon-192.png', 'icons/icon-512.png'];
const hash = crypto.createHash('sha1');
for (const f of files.slice(1)) hash.update(fs.readFileSync(f));
const v = hash.digest('hex').slice(0, 12);
fs.writeFileSync('sw.js', `// offline copy of the game (generated by build.js)
const CACHE = "sual-${v}", FILES = ${JSON.stringify(files)};
self.addEventListener("install", e => { self.skipWaiting(); e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES.map(f => new Request(f, { cache: "reload" }))))); });
self.addEventListener("activate", e => e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())));
self.addEventListener("fetch", e => {
  if (e.request.method !== "GET" || new URL(e.request.url).origin !== location.origin) return;
  e.respondWith(fetch(e.request).then(r => { if (r.ok) { const c = r.clone(); caches.open(CACHE).then(k => k.put(e.request, c)); } return r; })
    .catch(() => caches.match(e.request, { ignoreSearch: true }).then(r => r || caches.match("index.html"))));
});
`);
console.log('built', v, files.length, 'files');
